"""`/connect` — generate and register an MCP bridge for an application.

Most desktop applications do not speak MCP. This module closes that gap in the
two ways that actually work:

* **A file/API adapter** for applications whose real interface is a document
  plus a renderer. Kdenlive is the canonical case: its ``.kdenlive`` project is
  MLT XML and ``melt`` renders it, so the bridge edits the timeline and renders
  it rather than clicking a UI blindly.
* **A desktop adapter** for everything else: focus a window, type, press
  shortcuts, screenshot and OCR. It is deliberately honest about what it does
  not do — no synthetic mouse clicks without a backend, no privileged input.

The generated ``server.py`` is a thin launcher for :mod:`zimzilla.bridge`; the
bridge itself is shipped and tested once, not copied as a thousand-line string
into every install. It runs over MCP stdio, so ZimZilla's existing client finds
its tools exactly as it finds any other server's.

``bridge.json`` is the only per-app state: adapter, launch command, window
class, default project. It is written mode 600 because it sits beside the
credential profiles and may name a private path.
"""

from __future__ import annotations

import json
import os
import shutil
import sys
from dataclasses import dataclass
from pathlib import Path

from . import mcp

ZIMZILLA_HOME = Path(os.environ.get("ZIMZILLA_HOME") or (Path.home() / ".zimzilla"))
BRIDGES_DIR = ZIMZILLA_HOME / "bridges"

#: Apps with a real adapter. Everything else gets the desktop bridge.
ADAPTERS = {
    "kdenlive": {
        "adapter": "kdenlive",
        "command": ["kdenlive"],
        "window_class": "kdenlive",
        "blurb": "Kdenlive — MLT timeline edits, effects, transitions, melt render",
    },
    "desktop": {
        "adapter": "desktop",
        "command": [],
        "window_class": "",
        "blurb": "any desktop app — focus, type, shortcuts, screenshot, OCR",
    },
}

#: A name safe as a directory and as an MCP tool prefix.
_SAFE = set("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_-")


class ConnectError(Exception):
    """A bridge that cannot be generated, registered or connected."""


def _safe_name(name: str) -> str:
    cleaned = "".join(c if c in _SAFE else "-" for c in (name or "").strip().lower())
    cleaned = cleaned.strip("-_")
    return cleaned[:40] or "app"


def bridge_dir(name: str) -> Path:
    return BRIDGES_DIR / _safe_name(name)


def _launcher(adapter: str) -> str:
    """The generated server entry point.

    It imports the shipped bridge rather than embedding it. The fallback path
    is the checkout this file belongs to, for the editable-install case where
    the venv's ``sys.path`` does not already contain it.
    """
    root = Path(__file__).resolve().parent.parent
    return f'''#!/usr/bin/env python3
"""Generated by ZimZilla /connect — {adapter} MCP bridge.

Run by the ZimZilla MCP client over stdio. Re-run /connect {adapter} to
regenerate it; the implementation lives in zimzilla.bridge.
"""
import sys
from pathlib import Path

try:
    from zimzilla.bridge import main
except ImportError:  # editable checkout, launched from a bare interpreter
    sys.path.insert(0, {str(root)!r})
    from zimzilla.bridge import main

raise SystemExit(main({adapter!r}, Path(__file__).with_name("bridge.json")))
'''


def _write_bridge(name: str, config: dict) -> tuple[Path, Path]:
    directory = bridge_dir(name)
    directory.mkdir(parents=True, exist_ok=True)
    try:
        os.chmod(directory, 0o700)
    except OSError:
        pass
    server = directory / "server.py"
    server.write_text(_launcher(str(config["adapter"])), encoding="utf-8")
    try:
        os.chmod(server, 0o700)
    except OSError:
        pass
    cfg_path = directory / "bridge.json"
    fd = os.open(cfg_path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        json.dump(config, fh, indent=2)
        fh.write("\n")
    try:
        os.chmod(cfg_path, 0o600)
    except OSError:
        pass
    return server, cfg_path


def detect(spec: str) -> str:
    """The adapter for *spec*: kdenlive for Kdenlive, desktop otherwise."""
    base = Path(spec).name.lower()
    if base in ("kdenlive",) or spec.strip().lower() == "kdenlive":
        return "kdenlive"
    return "desktop"


def create_bridge(spec: str, *, name: str | None = None,
                  project: str = "", command: list[str] | None = None,
                  window_class: str = "", force: bool = False,
                  replace: bool = False) -> tuple[mcp.ServerConfig, dict]:
    """Generate one bridge and register it in ``mcp.json``.

    Returns ``(server config, bridge config)``. ``replace`` allows an existing
    generated bridge to be regenerated; a non-generated MCP server of the same
    name is never overwritten unless *force* is also set.
    """
    spec = (spec or "").strip()
    if not spec:
        raise ConnectError("which application? e.g. /connect kdenlive")
    adapter = detect(spec)
    app_name = _safe_name(name or (Path(spec).name if spec not in ADAPTERS
                                   else spec))
    cfg_name = _safe_name(name or app_name)
    existing = {s.name: s for s in mcp.load_config()}
    if cfg_name in existing:
        generated = (bridge_dir(cfg_name) / "server.py").is_file()
        # A generated bridge is ours to regenerate. A hand-written MCP entry
        # with the same name is not: replacing it needs an explicit --force.
        if not (force or (replace and generated)):
            raise ConnectError(
                f"an MCP server named {cfg_name!r} is already configured — "
                f"use /connect remove {cfg_name} first, or --replace"
                + (" (add --force for a non-generated entry)"
                   if not generated else ""))

    if command is None:
        if adapter == "kdenlive":
            command = list(ADAPTERS["kdenlive"]["command"])
        elif spec.lower() in ("neovim", "nvim") and shutil.which("nvim"):
            # `neovim` is the project name; the binary is `nvim`.
            command = ["nvim"]
        else:
            command = [spec]
    if adapter == "kdenlive":
        window_class = window_class or "kdenlive"
    else:
        window_class = window_class or app_name
    config = {
        "adapter": adapter,
        "app": app_name,
        "window_class": window_class,
        "command": list(command),
        "project": str(project or ""),
    }
    server, cfg_path = _write_bridge(cfg_name, config)
    entry = mcp.ServerConfig(
        name=cfg_name,
        command=sys.executable,
        args=[str(server)],
        enabled=True,
        timeout=120.0,
    )
    servers = [s for s in mcp.load_config() if s.name != cfg_name]
    servers.append(entry)
    try:
        mcp.save_config(servers)
    except OSError as e:
        raise ConnectError(f"could not write mcp.json: {e}") from e
    return entry, {"config": config, "server": str(server),
                   "config_path": str(cfg_path)}


def connect(cfg: mcp.ServerConfig) -> tuple[bool, str, list[str]]:
    """Connect one bridge and return its tool names. Blocking."""
    registry = mcp.registry()
    # A reconnect replaces a stale process, so close the old one first.
    old = registry.clients.get(cfg.name)
    if old is not None:
        try:
            old.close()
        except Exception:  # noqa: BLE001
            pass
        registry.clients.pop(cfg.name, None)
    registry.connect_all([cfg])
    error = registry.errors.get(cfg.name)
    if error:
        return False, error, []
    client = registry.clients.get(cfg.name)
    tools = [t.exposed_name for t in (client.tools if client else [])]
    return True, "connected", tools


def disconnect(name: str) -> bool:
    registry = mcp.registry()
    client = registry.clients.pop(_safe_name(name), None)
    if client is None:
        return False
    try:
        client.close()
    except Exception:  # noqa: BLE001
        pass
    return True


def remove(name: str) -> bool:
    """Remove the MCP entry and the generated bridge directory."""
    name = _safe_name(name)
    servers = mcp.load_config()
    kept = [s for s in servers if s.name != name]
    changed = len(kept) != len(servers)
    if changed:
        mcp.save_config(kept)
    disconnect(name)
    directory = bridge_dir(name)
    if directory.is_dir() and (directory / "server.py").is_file():
        shutil.rmtree(directory, ignore_errors=True)
        changed = True
    return changed


def generated() -> dict[str, dict]:
    """Every generated bridge, name -> its bridge config."""
    out: dict[str, dict] = {}
    try:
        entries = sorted(BRIDGES_DIR.iterdir())
    except OSError:
        return out
    for directory in entries:
        if not directory.is_dir():
            continue
        cfg_path = directory / "bridge.json"
        try:
            data = json.loads(cfg_path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if isinstance(data, dict):
            out[directory.name] = data
    return out


@dataclass(frozen=True)
class BridgeInfo:
    name: str
    app: str
    adapter: str
    command: tuple[str, ...]
    project: str
    path: Path


def list_bridges() -> list[BridgeInfo]:
    out: list[BridgeInfo] = []
    for name, data in sorted(generated().items()):
        command = data.get("command") or []
        out.append(BridgeInfo(
            name=name,
            app=str(data.get("app") or name),
            adapter=str(data.get("adapter") or "desktop"),
            command=tuple(str(c) for c in command if isinstance(c, str)),
            project=str(data.get("project") or ""),
            path=bridge_dir(name),
        ))
    return out
